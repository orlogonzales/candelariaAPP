<script>
document.addEventListener('DOMContentLoaded', () => {
    const btnSkeleton = document.getElementById('btn-demo-skeleton');
    const btnAccion = document.getElementById('btn-demo-accion');
    const contenedor = document.getElementById('contenedor-demo-interactivo');

    // 1. Demostración de Skeleton Loader en Carga Real
    if (btnSkeleton && contenedor) {
        btnSkeleton.addEventListener('click', async () => {
            // Mostrar Skeleton Table inmediatamente
            Skeleton.show(contenedor, 'table', { filas: 3, columnas: 3 });

            try {
                // Petición asincrónica real al endpoint API
                const respuesta = await window.CandelariaApi.get('estado');
                const datos = respuesta.datos;

                const tablaHtml = `
                    <div class="table-responsive">
                        <table class="table table-sm table-bordered align-middle mb-0 bg-white">
                            <thead class="table-primary">
                                <tr>
                                    <th>Parámetro</th>
                                    <th>Valor Backend</th>
                                    <th>Validación</th>
                                </tr>
                            </thead>
                            <tbody>
                                <tr>
                                    <td><strong>Plataforma</strong></td>
                                    <td>${datos.plataforma} ${datos.version}</td>
                                    <td><span class="badge bg-success">PASS</span></td>
                                </tr>
                                <tr>
                                    <td><strong>PHP</strong></td>
                                    <td>${datos.php}</td>
                                    <td><span class="badge bg-success">PASS</span></td>
                                </tr>
                                <tr>
                                    <td><strong>Frontend Oficial</strong></td>
                                    <td>${datos.frontend}</td>
                                    <td><span class="badge bg-success">PASS</span></td>
                                </tr>
                                <tr>
                                    <td><strong>Tipografía / Iconos</strong></td>
                                    <td>${datos.tipografia} &bull; ${datos.iconografia}</td>
                                    <td><span class="badge bg-success">PASS</span></td>
                                </tr>
                            </tbody>
                        </table>
                    </div>
                `;

                Skeleton.hide(contenedor, tablaHtml);
            } catch (error) {
                Skeleton.error(contenedor, 'Error al conectar con la API: ' + error.message, {
                    texto: 'Reintentar consulta',
                    accion: () => btnSkeleton.click()
                });
            }
        });
    }

    // 2. Demostración de Acción (Disabled + Spinner) y Resultado (SweetAlert2)
    if (btnAccion) {
        btnAccion.addEventListener('click', async () => {
            CandelariaUI.procesarBoton(btnAccion, 'Guardando operación...');

            try {
                // Petición real al endpoint para validar respuesta
                const respuesta = await window.CandelariaApi.get('estado');
                CandelariaUI.notificarExito(
                    'Operación asincrónica completada. El servidor respondió con éxito en ' + respuesta.datos.hora_servidor,
                    '¡Acción Procesada!'
                );
            } catch (error) {
                CandelariaUI.notificarError('No se pudo procesar la acción: ' + error.message);
            } finally {
                CandelariaUI.restaurarBoton(btnAccion);
            }
        });
    }
});
</script>
